package indexer

import (
	"context"
	"errors"
	"os"
	"path/filepath"

	"github.com/flanksource/uir/query"
	"github.com/flanksource/uir/storage"
	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
)

var _ = Describe("Git-backed external publication", func() {
	It("reads bound sources from a bare clone and stores only generated bytes", func(ctx SpecContext) {
		database := openIndexerSQLite(ctx)
		publication := prodPublication("initial", "100")
		root := canonicalTempDir()
		gitOutput(ctx, root, "init", "--quiet")
		original := publication.Documents[1].Source
		native := "rules/Calc\tcopy\n.xml"
		Expect(os.MkdirAll(filepath.Join(root, "rules"), 0o755)).To(Succeed())
		Expect(os.WriteFile(filepath.Join(root, native), []byte(original), 0o600)).To(Succeed())
		gitOutput(ctx, root, "add", "rules")
		gitOutput(ctx, root, "-c", "user.name=test", "-c", "user.email=test@example.org", "commit", "--quiet", "-m", "fixture")
		sha := gitOutput(ctx, root, "rev-parse", "HEAD")
		bare := filepath.Join(canonicalTempDir(), "source.git")
		gitOutput(ctx, root, "clone", "--bare", root, bare)
		publication.Location.RepositoryURI = bare
		publication.Options = PublishOptions{GitCommit: sha, Producer: "git-v1", Historical: true}
		publication.Documents[1].GitPath = native
		result := publish(ctx, database, publication)
		var count int64
		Expect(database.Model(&storage.SourceBlob{}).Where("content_hash = ?", publication.Documents[1].ContentHash).Count(&count).Error).To(Succeed())
		Expect(count).To(BeZero())
		pipeline, err := query.NewPipeline(database)
		Expect(err).NotTo(HaveOccurred())
		contents, err := pipeline.ReadModuleSources(ctx, query.ModuleSourcesOptions{SnapshotID: result.SnapshotID, Paths: []string{publication.Documents[1].PathKey, publication.Documents[0].PathKey}})
		Expect(err).NotTo(HaveOccurred())
		Expect(contents[0].Content).To(Equal(original))
		Expect(contents[0].Origin).To(Equal("git"))
		Expect(contents[1].Content).To(Equal(publication.Documents[0].Source))
		Expect(contents[1].Origin).To(Equal("snapshot"))
		readerFailure := errors.New("repository unavailable")
		failed, err := query.NewPipeline(database, query.WithGitSourceReader(func(context.Context, query.GitSourceOptions) ([][]byte, error) {
			return nil, readerFailure
		}))
		Expect(err).NotTo(HaveOccurred())
		_, err = failed.ReadModuleSources(ctx, query.ModuleSourcesOptions{SnapshotID: result.SnapshotID, Paths: []string{publication.Documents[1].PathKey}})
		Expect(errors.Is(err, readerFailure)).To(BeTrue())
		wrong, err := query.NewPipeline(database, query.WithGitSourceReader(func(_ context.Context, options query.GitSourceOptions) ([][]byte, error) {
			Expect(options).To(Equal(query.GitSourceOptions{RepositoryURI: bare, Commit: sha, Paths: []string{native}}))
			return [][]byte{[]byte("wrong content")}, nil
		}))
		Expect(err).NotTo(HaveOccurred())
		_, err = wrong.ReadModuleSources(ctx, query.ModuleSourcesOptions{SnapshotID: result.SnapshotID, Paths: []string{publication.Documents[1].PathKey}})
		Expect(err).To(MatchError(ContainSubstring("does not match indexed content hash")))

		publication.Documents[1].GitPath = "rules/moved.xml"
		changed := publish(ctx, database, publication)
		Expect(changed.SnapshotID).NotTo(Equal(result.SnapshotID))
		Expect(database.Model(&storage.SourceRevision{}).Where("path_key = ?", publication.Documents[1].PathKey).Count(&count).Error).To(Succeed())
		Expect(count).To(Equal(int64(2)))
		old, err := pipeline.ReadModuleSource(ctx, result.SnapshotID, publication.Documents[1].PathKey)
		Expect(err).NotTo(HaveOccurred())
		Expect(old.Content).To(Equal(original))
		_, err = pipeline.ReadModuleSource(ctx, changed.SnapshotID, publication.Documents[1].PathKey)
		Expect(err).To(MatchError(ContainSubstring("missing")))
		publication.Location.RepositoryURI = root
		_, err = Publish(ctx, database, publication)
		Expect(err).To(MatchError(ContainSubstring("already binds repository")))
	})
})
